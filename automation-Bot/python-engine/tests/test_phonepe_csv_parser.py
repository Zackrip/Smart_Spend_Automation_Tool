import csv
import sys
from pathlib import Path
from decimal import Decimal

import pytest

# Allow running pytest from the python-engine project root.
PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.phonepe_csv_parser import extract_phonepe_csv_transactions


def test_parses_phonepe_csv_with_preamble_and_footer():
    csv_text = '''Transaction Statement for 0000000000
Duration,"11 Nov, 2025 - 11 Nov, 2026"

Date,Time,Transaction Details,Transaction ID,UTR,Transaction Type,Credit/debit instrument,Amount
"Nov 10, 2026","10:44 pm","Payment to Google","TXN001","UTR001","DEBIT","Paid by XXXXX1883","59"
"Nov 10, 2026","12:17 am","Received from Kanha Ki Didi","TXN002","UTR002","CREDIT","Credited to XXXXX1883","302"
Disclaimer: This statement is generated by PhonePe.
'''

    transactions = extract_phonepe_csv_transactions(csv_text.encode("utf-8"))

    assert len(transactions) == 2
    assert transactions[0]["transaction_date"] == "2026-11-10"
    assert transactions[0]["transaction_time"] == "22:44:00"
    assert transactions[0]["merchant"] == "Google"
    assert transactions[0]["transaction_type"] == "expense"
    assert transactions[0]["amount"] == Decimal("59")
    assert transactions[0]["payment_source"] == "XXXXX1883"
    assert transactions[0]["source"] == "phonepe_csv"
    assert transactions[1]["merchant"] == "Kanha Ki Didi"
    assert transactions[1]["transaction_type"] == "credit"
    assert transactions[1]["credited_to"] == "XXXXX1883"


def test_rejects_csv_without_phonepe_header():
    with pytest.raises(ValueError, match="header was not found"):
        extract_phonepe_csv_transactions(b"hello,world\n1,2\n")


def test_rejects_invalid_amount_in_transaction_row():
    csv_text = '''Date,Time,Transaction Details,Transaction ID,UTR,Transaction Type,Credit/debit instrument,Amount
"Nov 10, 2026","10:44 pm","Payment to Google","TXN001","UTR001","DEBIT","Paid by XXXXX1883","not-a-number"
'''
    with pytest.raises(ValueError, match="Invalid transaction amount"):
        extract_phonepe_csv_transactions(csv_text.encode("utf-8"))


def test_supports_utf8_bom_and_commas_in_amount():
    csv_text = '''Date,Time,Transaction Details,Transaction ID,UTR,Transaction Type,Credit/debit instrument,Amount
"Nov 10, 2026","10:44 pm","Payment to Store","TXN001","UTR001","DEBIT","Paid by XXXXX1883","1,250.50"
'''
    transactions = extract_phonepe_csv_transactions(("\ufeff" + csv_text).encode("utf-8"))
    assert transactions[0]["amount"] == Decimal("1250.50")
 